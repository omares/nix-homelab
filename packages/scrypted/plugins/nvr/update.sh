#!/usr/bin/env nix-shell
#!nix-shell -i bash -p curl jq unzip nix gnutar gzip coreutils gnugrep gnused

# Update script for scrypted-plugin-nvr
# Regenerates versions.nix: the latest plugin from npm plus the libav addon release the plugin
# bundle downloads at runtime.
#
# Usage: ./update.sh

set -euo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")"

# process.versions.modules of Node 22, see package.nix
NODE_ABI=127

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

echo "==> Fetching @scrypted/nvr..."
PLUGIN_INFO=$(curl -sf "https://registry.npmjs.org/@scrypted/nvr/latest")
PLUGIN_VERSION=$(jq -r '.version' <<<"$PLUGIN_INFO")
PLUGIN_HASH=$(jq -r '.dist.integrity' <<<"$PLUGIN_INFO")
curl -sfL "$(jq -r '.dist.tarball' <<<"$PLUGIN_INFO")" | tar xz -C "$tmp"
unzip -q "$tmp/package/dist/plugin.zip" '*.js' -d "$tmp/plugin"
echo "    @scrypted/nvr: $PLUGIN_VERSION"

# The bundle embeds the package.json of @scrypted/libav
mapfile -t LIBAV_VERSIONS < <(grep -ohE 'name:"@scrypted/libav",version:"[^"]+"' "$tmp"/plugin/*.js \
  | sed -E 's/.*version:"([^"]+)"/\1/' | sort -u)
if [[ ${#LIBAV_VERSIONS[@]} -ne 1 ]]; then
  echo "ERROR: expected one @scrypted/libav version in the nvr bundle, found: ${LIBAV_VERSIONS[*]:-none}" >&2
  exit 1
fi
LIBAV_VERSION="${LIBAV_VERSIONS[0]}"

LIBAV_URL="https://github.com/scryptedapp/libav/releases/download/v${LIBAV_VERSION}/libav-v${LIBAV_VERSION}-node-v${NODE_ABI}-linux-x64.tar.gz"
LIBAV_HASH=$(nix store prefetch-file --json "$LIBAV_URL" | jq -r '.hash')
echo "    @scrypted/libav: $LIBAV_VERSION"

cat >versions.nix <<EOF
# Auto-generated by update.sh - do not edit manually
{
  # Plugin version (@scrypted/nvr)
  version = "$PLUGIN_VERSION";
  # npm integrity hash
  hash = "$PLUGIN_HASH";

  # libav addon release used by this plugin version
  libav = {
    version = "$LIBAV_VERSION";
    hash = "$LIBAV_HASH";
  };
}
EOF

echo "==> Done!"
