#!/usr/bin/env nix-shell
#!nix-shell -i bash -p curl jq uv unzip nix gnutar gzip coreutils

# Update script for scrypted-plugin-openvino
# Regenerates versions.nix: the latest plugin from npm plus the PyPI wheels pinned by the
# plugin's own requirements.txt, resolved for Python 3.12 on x86_64 Linux.
#
# Usage: ./update.sh

set -euo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")"

# Taken from PyPI wheels: everything that depends on numpy (nixpkgs' numpy is too new for
# openvino) and packages missing from the binary cache. The rest comes from nixpkgs.
WHEELS=(
  numpy
  openvino
  openvino-telemetry
  opencv-python-headless
  transformers
  huggingface-hub
  tokenizers
  safetensors
  hf-xet
)

# Models the plugin loads via snapshot_download (scrypted/plugin-models, openvino/<model>/*).
# Detection model picked by the plugin for Intel iGPUs/CPUs without Arc or Iris Xe.
MODELS=(
  scrypted_yolov9t_relu_test_int8
  scrypted_yolov9t_relu_face_int8
  inception_resnet_v1
  craft
  vgg_english_g2
  scrypted_yolov9t_seg_relu_int8
  clip
)

# Files CLIPProcessor.from_pretrained reads from the HF cache
CLIP_PROCESSOR_REPO="openai/clip-vit-base-patch32"
CLIP_PROCESSOR_FILES=(
  config.json
  merges.txt
  preprocessor_config.json
  special_tokens_map.json
  tokenizer.json
  tokenizer_config.json
  vocab.json
)

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

echo "==> Fetching @scrypted/openvino..."
PLUGIN_INFO=$(curl -sf "https://registry.npmjs.org/@scrypted/openvino/latest")
PLUGIN_VERSION=$(jq -r '.version' <<<"$PLUGIN_INFO")
PLUGIN_HASH=$(jq -r '.dist.integrity' <<<"$PLUGIN_INFO")
curl -sfL "$(jq -r '.dist.tarball' <<<"$PLUGIN_INFO")" | tar xz -C "$tmp"
unzip -p "$tmp/package/dist/plugin.zip" requirements.txt >"$tmp/requirements.txt"
echo "    @scrypted/openvino: $PLUGIN_VERSION"

echo "==> Resolving requirements.txt..."
uv pip compile --quiet --no-header --no-annotate \
  --python-version 3.12 --python-platform x86_64-manylinux_2_28 \
  "$tmp/requirements.txt" -o "$tmp/lock.txt"

wheel_entry() {
  local name="$1" version file
  version=$(grep -i "^${name}==" "$tmp/lock.txt" | cut -d= -f3)
  if [[ -z "$version" ]]; then
    echo "ERROR: $name is not part of the resolved requirements" >&2
    exit 1
  fi

  file=$(curl -sf "https://pypi.org/pypi/${name}/${version}/json" | jq -c '
    [.urls[] | select(.packagetype == "bdist_wheel")] as $w
    | ([$w[] | select(.filename | test("-cp312-cp312-manylinux.*x86_64"))]
      + [$w[] | select(.filename | test("-abi3-manylinux.*x86_64"))]
      + [$w[] | select(.filename | test("-py3-none-any"))])[0]')
  if [[ "$file" == "null" ]]; then
    echo "ERROR: no x86_64 cp312 wheel for $name $version" >&2
    exit 1
  fi

  echo "    $name: $version" >&2
  cat <<EOF
    ${name} = {
      version = "${version}";
      url = "$(jq -r '.url' <<<"$file")";
      hash = "$(nix hash convert --hash-algo sha256 --to sri "$(jq -r '.digests.sha256' <<<"$file")")";
    };
EOF
}

ENTRIES=""
for name in "${WHEELS[@]}"; do
  ENTRIES+=$(wheel_entry "$name")$'\n'
done

# Prints `"<file>" = "<sri hash>";` for a file of a HF repo at a commit.
# LFS files carry their sha256 in the tree listing, small git files are downloaded and hashed.
hf_file_entry() {
  local indent="$1" repo="$2" commit="$3" path="$4" file="$5" sha256="$6"
  if [[ -z "$sha256" ]]; then
    sha256=$(curl -sfL "https://huggingface.co/${repo}/resolve/${commit}/${path}" | sha256sum | cut -d' ' -f1)
  fi
  echo "${indent}\"${file}\" = \"$(nix hash convert --hash-algo sha256 --to sri "$sha256")\";"
}

echo "==> Fetching model hashes..."
MODELS_COMMIT=$(curl -sf "https://huggingface.co/api/models/scrypted/plugin-models" | jq -r '.sha')
echo "    scrypted/plugin-models: $MODELS_COMMIT"
MODEL_ENTRIES=""
for model in "${MODELS[@]}"; do
  echo "    $model" >&2
  MODEL_ENTRIES+="      ${model} = {"$'\n'
  while IFS=$'\t' read -r path sha256; do
    file="${path##*/}"
    # The plugin only loads the full precision CLIP models
    [[ "$model" == clip && "$file" == *_int8* ]] && continue
    MODEL_ENTRIES+=$(hf_file_entry "        " scrypted/plugin-models "$MODELS_COMMIT" "$path" "$file" "$sha256")$'\n'
  done < <(curl -sf "https://huggingface.co/api/models/scrypted/plugin-models/tree/${MODELS_COMMIT}/openvino/${model}" \
    | jq -r '.[] | select(.type == "file") | [.path, (.lfs.oid // "")] | @tsv')
  MODEL_ENTRIES+="      };"$'\n'
done

CLIP_COMMIT=$(curl -sf "https://huggingface.co/api/models/${CLIP_PROCESSOR_REPO}" | jq -r '.sha')
echo "    ${CLIP_PROCESSOR_REPO}: $CLIP_COMMIT"
CLIP_ENTRIES=""
for file in "${CLIP_PROCESSOR_FILES[@]}"; do
  CLIP_ENTRIES+=$(hf_file_entry "      " "$CLIP_PROCESSOR_REPO" "$CLIP_COMMIT" "$file" "$file" "")$'\n'
done

cat >versions.nix <<EOF
# Auto-generated by update.sh - do not edit manually
{
  # Plugin version (@scrypted/openvino)
  version = "$PLUGIN_VERSION";
  # npm integrity hash
  hash = "$PLUGIN_HASH";

  # PyPI wheels resolved from the plugin's requirements.txt
  wheels = {
${ENTRIES}  };

  # scrypted/plugin-models files per model (openvino/<model>/<file>)
  models = {
    commit = "$MODELS_COMMIT";
    files = {
${MODEL_ENTRIES}    };
  };

  # HF cache files for CLIPProcessor.from_pretrained("${CLIP_PROCESSOR_REPO}")
  clipProcessor = {
    repo = "${CLIP_PROCESSOR_REPO}";
    commit = "$CLIP_COMMIT";
    files = {
${CLIP_ENTRIES}    };
  };
}
EOF

echo "==> Provided by nixpkgs (resolved versions for comparison):"
WHEEL_PATTERN=$(printf '%s|' "${WHEELS[@]}")
grep -viE "^(${WHEEL_PATTERN%|})==" "$tmp/lock.txt" | sed 's/^/    /'
